"""Generate the data dictionary (docs/data-dictionary.md and .json) from openlending.schema."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from openlending.config import Settings
from openlending.schema import TABLE_DESCRIPTIONS, TABLE_KEYS, TABLES, Col


def output_columns(c: Col) -> list[dict[str, Any]]:
    """The physical columns one spec produces (value, then label / na_reason companions)."""
    cols: list[dict[str, Any]] = [
        {
            "name": c.name,
            "type": c.sql_type,
            "kind": c.kind,
            "nullable": c.nullable,
            "description": c.description,
        }
    ]
    if c.domain:
        cols[0]["codes"] = {str(k): v for k, v in sorted(c.domain.items())}
    if c.allowed:
        cols[0]["allowed_values"] = list(c.allowed)
    if c.label and c.domain:
        cols.append(
            {
                "name": f"{c.name}_label",
                "type": "VARCHAR",
                "kind": "label",
                "nullable": True,
                "description": f"Label for {c.name} (NULL when the code is not in the code list).",
            }
        )
    if c.na_reason:
        cols.append(
            {
                "name": f"{c.name}_na_reason",
                "type": "VARCHAR",
                "kind": "na_reason",
                "nullable": True,
                "description": f"Why {c.name} is NULL: 'NA' (not applicable) or 'Exempt' "
                "(partial exemption under EGRRCPA); NULL when a value is present.",
            }
        )
    return cols


def dictionary() -> dict[str, Any]:
    return {
        name: {
            "description": TABLE_DESCRIPTIONS[name],
            "primary_key": TABLE_KEYS[name],
            "columns": [oc for c in cols for oc in output_columns(c)],
        }
        for name, cols in TABLES.items()
    }


def _md_codes(col: dict[str, Any]) -> str:
    if "codes" in col:
        return "; ".join(f"{k} {v}" for k, v in col["codes"].items())
    if "allowed_values" in col:
        return "; ".join(col["allowed_values"])
    return ""


def markdown(d: dict[str, Any]) -> str:
    lines = [
        "# Data dictionary",
        "",
        "Generated by `openlending docs` from `src/openlending/schema.py`; do not edit by hand.",
        "The same content is in [data-dictionary.json](data-dictionary.json). Definitional "
        "changes across years are in [changes-over-time.md](changes-over-time.md).",
        "",
    ]
    for name, t in d.items():
        lines += [
            f"## {name}",
            "",
            t["description"],
            "",
            f"Key: `{', '.join(t['primary_key'])}`. Columns: {len(t['columns'])}.",
            "",
            "| Column | Type | Description | Codes / values |",
            "|---|---|---|---|",
        ]
        for c in t["columns"]:
            desc = c["description"].replace("|", "/")
            codes = _md_codes(c).replace("|", "/")
            lines.append(f"| `{c['name']}` | {c['type']} | {desc} | {codes} |")
        lines.append("")
    return "\n".join(lines)


def write_dictionary(s: Settings) -> list[Path]:
    d = dictionary()
    s.docs_dir.mkdir(parents=True, exist_ok=True)
    md = s.docs_dir / "data-dictionary.md"
    js = s.docs_dir / "data-dictionary.json"
    md.write_text(markdown(d))
    js.write_text(json.dumps(d, indent=2) + "\n")
    return [md, js]
